"""Writes src/tok/unicode_tables.cpp from Python's own Unicode database (standard library only).

    python3 tools/gen_unicode_tables.py            rewrite the file; the Unicode version is printed and embedded

The tokenizer needs four facts per code point and nothing else:
  - the general category class: letter (L*), mark (M*), number (N*);
  - the White_Space property (a fixed, short list from the Unicode PropList; regex \\s in the reference tokenizer);
  - the canonical combining class (for NFC);
  - the canonical decomposition and the primary composites (for NFC; Hangul syllables are computed, not tabled).
The tables are sorted ranges or sorted pairs so the C++ side looks them up with a binary search.
"""
import os
import sys
import unicodedata

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
OUT = os.path.join(ROOT, 'src', 'tok', 'unicode_tables.cpp')
MAX_CP = 0x110000

# Unicode PropList.txt, White_Space (stable since Unicode 6.3)
WHITE_SPACE = [(0x0009, 0x000D), (0x0020, 0x0020), (0x0085, 0x0085), (0x00A0, 0x00A0), (0x1680, 0x1680),
               (0x2000, 0x200A), (0x2028, 0x2029), (0x202F, 0x202F), (0x205F, 0x205F), (0x3000, 0x3000)]

S_BASE, L_BASE, V_BASE, T_BASE = 0xAC00, 0x1100, 0x1161, 0x11A7
S_COUNT = 11172


def ranges(pred):
    out = []
    start = None
    for cp in range(MAX_CP):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX_CP - 1))
    return out


def cat(cp):
    return unicodedata.category(chr(cp))


def full_decomposition(cp):
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith('<'):
        return [cp]
    out = []
    for part in d.split():
        out.extend(full_decomposition(int(part, 16)))
    return out


def main():
    letters = ranges(lambda cp: cat(cp).startswith('L'))
    marks = ranges(lambda cp: cat(cp).startswith('M'))
    numbers = ranges(lambda cp: cat(cp).startswith('N'))

    ccc = []  # (lo, hi, class) runs of equal non-zero class
    run = None
    for cp in range(MAX_CP):
        c = unicodedata.combining(chr(cp))
        if c and run and run[2] == c and run[1] == cp - 1:
            run = (run[0], cp, c)
            continue
        if run:
            ccc.append(run)
            run = None
        if c:
            run = (cp, cp, c)
    if run:
        ccc.append(run)

    decomp = []  # (cp, [code points]) for every non-Hangul code point with a canonical decomposition
    compose = []  # (first, second, composite) for every primary composite
    for cp in range(MAX_CP):
        if S_BASE <= cp < S_BASE + S_COUNT:
            continue
        d = unicodedata.decomposition(chr(cp))
        if not d or d.startswith('<'):
            continue
        decomp.append((cp, full_decomposition(cp)))
        parts = [int(p, 16) for p in d.split()]
        # a primary composite: a two-part canonical decomposition that NFC recomposes (excludes the composition
        # exclusions and the singletons/non-starter decompositions)
        if len(parts) == 2 and unicodedata.normalize('NFC', chr(parts[0]) + chr(parts[1])) == chr(cp):
            compose.append((parts[0], parts[1], cp))
    compose.sort()

    pool = []
    index = []
    for cp, seq in decomp:
        index.append((cp, len(pool), len(seq)))
        pool.extend(seq)

    def fmt_ranges(name, rs):
        body = ',\n'.join('    {0x%X, 0x%X}' % r for r in rs)
        return f'const CpRange {name}[] = {{\n{body},\n}};\nconst std::size_t {name}_count = {len(rs)};\n'

    lines = []
    lines.append('// provenance: generated by tools/gen_unicode_tables.py from Python ' + sys.version.split()[0] +
                 ' unicodedata (Unicode ' + unicodedata.unidata_version + ')')
    lines.append('// Copyright (c) 2026 John Lipka and the Pelias contributors')
    lines.append('//')
    lines.append('// Do not edit: rerun the generator. Sorted tables for binary search (tok/unicode.h).')
    lines.append('#include "tok/unicode.h"')
    lines.append('')
    lines.append('namespace pelias::tok::tables {')
    lines.append('')
    lines.append(f'const char* const kUnicodeVersion = "{unicodedata.unidata_version}";')
    lines.append('')
    lines.append(fmt_ranges('kLetter', letters))
    lines.append(fmt_ranges('kMark', marks))
    lines.append(fmt_ranges('kNumber', numbers))
    lines.append(fmt_ranges('kWhiteSpace', WHITE_SPACE))
    body = ',\n'.join('    {0x%X, 0x%X, %d}' % r for r in ccc)
    lines.append(f'const CccRange kCcc[] = {{\n{body},\n}};\nconst std::size_t kCcc_count = {len(ccc)};\n')
    body = ',\n'.join('    {0x%X, %d, %d}' % r for r in index)
    lines.append(f'const DecompEntry kDecomp[] = {{\n{body},\n}};\nconst std::size_t kDecomp_count = {len(index)};\n')
    chunks = [', '.join('0x%X' % v for v in pool[i:i + 12]) for i in range(0, len(pool), 12)]
    body = ',\n'.join('    ' + c for c in chunks)
    lines.append(f'const char32_t kDecompPool[] = {{\n{body},\n}};\nconst std::size_t kDecompPool_count = {len(pool)};\n')
    body = ',\n'.join('    {0x%X, 0x%X, 0x%X}' % r for r in compose)
    lines.append(f'const ComposePair kCompose[] = {{\n{body},\n}};\nconst std::size_t kCompose_count = {len(compose)};\n')
    lines.append('}  // namespace pelias::tok::tables')
    lines.append('')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print(f'Unicode {unicodedata.unidata_version}: letters {len(letters)} ranges, marks {len(marks)}, numbers {len(numbers)}, '
          f'ccc {len(ccc)}, decompositions {len(index)} ({len(pool)} code points), compositions {len(compose)}')


if __name__ == '__main__':
    main()
