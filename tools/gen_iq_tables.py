"""Writes src/quant/iq_tables.cpp: the lookup grids that define the IQ1 / IQ2 / IQ3 GGUF formats (standard library only).

    python3 tools/gen_iq_tables.py PATH/ggml/src/ggml-common.h

The grids are data, not code: the format's author chose the points by an offline search over real weights, so there
is no formula that rebuilds them, and a file written in one of these formats decodes correctly only with exactly these
numbers. This tool reads them from the reference library's source (MIT; THIRD_PARTY_NOTICES.md, "Data compiled into
the product") and writes them as Pelias's own table file. The sign tables that do follow from a rule (each 7-bit sign
pattern with its parity as the eighth bit; the eight bit masks) are computed here and checked against the reference's
copies, so a mismatch stops the tool.
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
OUT = os.path.join(ROOT, 'src', 'quant', 'iq_tables.cpp')

GRIDS = [  # (name in the reference, C type, expected count)
    ('iq2xxs_grid', 'std::uint64_t', 256),
    ('iq2xs_grid', 'std::uint64_t', 512),
    ('iq2s_grid', 'std::uint64_t', 1024),
    ('iq3xxs_grid', 'std::uint32_t', 256),
    ('iq3s_grid', 'std::uint32_t', 512),
    ('iq1s_grid', 'std::uint64_t', 2048),
]


def table(src, name):
    m = re.search(r'GGML_TABLE_BEGIN\(\w+, ' + name + r', \w+\)(.*?)GGML_TABLE_END\(\)', src, re.S)
    if not m:
        sys.exit(f'{name} not found')
    return [int(v, 0) for v in re.findall(r'-?0x[0-9a-fA-F]+|-?\d+', m.group(1))]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    path = sys.argv[1]
    src = open(path, encoding='utf-8').read()
    commit = ''
    git_head = os.path.join(os.path.dirname(path), '..', '..', '.git', 'HEAD')
    if os.path.exists(git_head):
        head = open(git_head).read().strip()
        if head.startswith('ref: '):
            ref = os.path.join(os.path.dirname(git_head), head[5:])
            head = open(ref).read().strip() if os.path.exists(ref) else head
        commit = head[:40]

    # the rule-based tables, computed and checked
    signs = [i | ((bin(i).count('1') & 1) << 7) for i in range(128)]
    masks = [1 << j for j in range(8)]
    if table(src, 'ksigns_iq2xs') != signs or table(src, 'kmask_iq2xs') != masks:
        sys.exit('the reference sign tables do not follow the parity rule: check the source')

    lines = [
        '// provenance: generated by tools/gen_iq_tables.py; the grid values are data read from ggml ggml/src/ggml-common.h'
        + (f' at commit {commit}' if commit else '') + ' (MIT; THIRD_PARTY_NOTICES.md)',
        '// Copyright (c) 2026 John Lipka and the Pelias contributors',
        '//',
        '// Do not edit: rerun the generator. Each grid entry packs 8 (uint64) or 4 (uint32) byte values, lowest byte first.',
        '#include "quant/iq_tables.h"',
        '',
        'namespace pelias::quant::iq {',
        '',
        '// computed by the generator (sign pattern i with its parity as bit 7; one bit per position)',
        'const std::uint8_t kSigns[128] = {' + ', '.join(str(v) for v in signs) + '};',
        'const std::uint8_t kMask[8] = {' + ', '.join(str(v) for v in masks) + '};',
        '',
    ]
    names = {'iq2xxs_grid': 'kIq2xxsGrid', 'iq2xs_grid': 'kIq2xsGrid', 'iq2s_grid': 'kIq2sGrid',
             'iq3xxs_grid': 'kIq3xxsGrid', 'iq3s_grid': 'kIq3sGrid', 'iq1s_grid': 'kIq1sGrid'}
    for name, ctype, count in GRIDS:
        vals = table(src, name)
        if len(vals) != count:
            sys.exit(f'{name}: {len(vals)} values, expected {count}')
        width = 16 if ctype == 'std::uint64_t' else 8
        rows = []
        per = 4 if width == 16 else 8
        for k in range(0, count, per):
            rows.append('    ' + ', '.join(f'0x{v:0{width}x}' for v in vals[k:k + per]))
        lines.append(f'const {ctype} {names[name]}[{count}] = {{')
        lines.append(',\n'.join(rows) + ',')
        lines.append('};')
        lines.append('')
    lines.append('}  // namespace pelias::quant::iq')
    lines.append('')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print(f'wrote {OUT}: ' + ', '.join(f'{n} {c}' for n, _, c in GRIDS) + (f' (reference commit {commit})' if commit else ''))


if __name__ == '__main__':
    main()
