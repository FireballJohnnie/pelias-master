# Compiles shaders/*.comp to SPIR-V with glslang and writes src/shaders_spv.h.
# Usage: python tools/embed_spirv.py <path-to-glslang>
import pathlib, struct, subprocess, sys
root = pathlib.Path(__file__).resolve().parent.parent
glslang = sys.argv[1]
out = ["// provenance: generated by tools/embed_spirv (glslang from the .comp sources in shaders/)",
       "// Copyright (c) 2026 John Lipka and the Pelias contributors",
       "#pragma once", "#include <cstdint>", "#include <cstddef>"]
for name in ("tiny", "doorbell", "doorbell_atomic", "doorbell_mm", "busy"):
    src, spv = root / "shaders" / f"{name}.comp", root / "shaders" / f"{name}.spv"
    subprocess.run([glslang, "-V", "--target-env", "vulkan1.2", "-o", str(spv), str(src)], check=True, stdout=subprocess.DEVNULL)
    words = struct.unpack(f"<{spv.stat().st_size // 4}I", spv.read_bytes())
    # Device-scope atomics under the Vulkan memory model need the VulkanMemoryModelDeviceScope capability (5346);
    # this glslang build leaves it out, so add it after the last OpCapability when Device scope (1) is used.
    words = list(words)
    if 5345 in [words[i + 1] for i in range(5, len(words) - 1) if words[i] == (2 << 16 | 17)] and \
       (2 << 16 | 17, 5346) not in list(zip(words, words[1:])):
        last = max(i for i in range(5, len(words) - 1) if words[i] == (2 << 16 | 17))
        words[last + 2:last + 2] = [2 << 16 | 17, 5346]
        spv.write_bytes(struct.pack(f"<{len(words)}I", *words))
    out.append(f"static const uint32_t kSpv_{name}[] = {{")
    for i in range(0, len(words), 8):
        out.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",")
    out.append("};")
    out.append(f"static const size_t kSpv_{name}_size = sizeof(kSpv_{name});")
(root / "src" / "shaders_spv.h").write_text("\n".join(out) + "\n")
print("wrote src/shaders_spv.h")
